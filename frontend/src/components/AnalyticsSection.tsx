import { ReloadOutlined } from '@ant-design/icons'
import { Alert, Button, Card, Col, Row, Select, Space, Statistic, Typography } from 'antd'
import { useState } from 'react'
import { errorMessage } from '../api/client'
import { useAnalyticsOverview, useAnalyticsUsers, useRefreshAnalytics } from '../hooks/useAnalytics'
import { conceptScoreOption, funnelOption, progressOption } from '../lib/analyticsCharts'
import { pct } from '../lib/weakSpots'
import Chart from './Chart'
import QueryState from './QueryState'

const num = (x: number | null, digits = 1) => (x == null ? '—' : x.toFixed(digits))

/** Pipeline-backed learning analytics: progress, concept strengths and the practice funnel. */
export default function AnalyticsSection() {
  const users = useAnalyticsUsers()
  const [selected, setSelected] = useState<number>()
  const userId = selected ?? users.data?.[0]?.id
  const overview = useAnalyticsOverview(userId)
  const refresh = useRefreshAnalytics()
  const data = overview.data
  const hasData = !!data && data.pipeline_ready && data.learner_daily.length > 0

  return (
    <Card
      title="Learning analytics"
      extra={
        <Space wrap>
          <Select
            style={{ minWidth: 220 }}
            aria-label="Learner"
            placeholder="Select a learner"
            value={userId}
            onChange={setSelected}
            loading={users.isLoading}
            options={(users.data ?? []).map((u) => ({ value: u.id, label: u.display_name }))}
          />
          <Button icon={<ReloadOutlined />} loading={refresh.isPending} onClick={() => refresh.mutate()}>
            Refresh analytics
          </Button>
        </Space>
      }
    >
      <Space direction="vertical" size="middle" style={{ width: '100%' }}>
        {refresh.error && <Alert type="error" showIcon message={`Refresh failed: ${errorMessage(refresh.error)}`} />}
        {data?.is_synthetic && (
          <Alert type="warning" showIcon message="Synthetic demo data: generated by a script, not real usage." />
        )}
        <QueryState isLoading={users.isLoading || overview.isLoading} error={users.error ?? overview.error}>
          {!hasData ? (
            <Typography.Paragraph type="secondary" style={{ margin: 0 }}>
              {data && !data.pipeline_ready
                ? 'The analytics tables have not been built yet. '
                : 'There are no completed attempts for this learner yet. '}
              Click “Refresh analytics” (or run <code>python -m pipeline.run</code>), and seed synthetic demo data
              with <code>python -m pipeline.seed_demo</code> if you want something to look at.
            </Typography.Paragraph>
          ) : (
            <Space direction="vertical" size="large" style={{ width: '100%' }}>
              <Row gutter={[16, 16]}>
                <Col xs={12} md={6}>
                  <Statistic title="Completed attempts" value={data.headline.completed_attempts} />
                </Col>
                <Col xs={12} md={6}>
                  <Statistic
                    title="Independence"
                    value={data.headline.independence_rate == null ? '—' : pct(data.headline.independence_rate)}
                    suffix={data.headline.independence_rate == null ? undefined : '%'}
                  />
                </Col>
                <Col xs={12} md={6}>
                  <Statistic title="Avg hint level" value={num(data.headline.avg_hint_level)} />
                </Col>
                <Col xs={12} md={6}>
                  <Statistic title="Gap concepts" value={data.headline.gap_concepts} />
                </Col>
              </Row>
              <div>
                <Typography.Title level={5}>Independence and hint use over time</Typography.Title>
                <Chart option={progressOption(data.learner_daily)} height={300} />
              </div>
              <div>
                <Typography.Title level={5}>Average effective score by concept (red = gap)</Typography.Title>
                <Chart option={conceptScoreOption(data.concept_summary)} />
              </div>
              {data.funnel.map((f) => (
                <div key={f.document_id}>
                  <Typography.Title level={5}>Practice funnel: {f.document_title ?? `Document ${f.document_id}`}</Typography.Title>
                  <Chart option={funnelOption(f)} height={260} />
                </div>
              ))}
            </Space>
          )}
        </QueryState>
      </Space>
    </Card>
  )
}
